    weak var compositor: RecordingFrameCompositor?
    weak var state: RecordingCompositionState?
    weak var controller: RecordingOverlayController?
    var liveObjectCount: Int { [writer != nil, compositor != nil, state != nil, controller != nil].filter { $0 }.count }
}

private final class RecordingCompositionSmokeClock: @unchecked Sendable {
    private let lock = NSLock()
    private var time: CMTime
    init(_ seconds: Double) { time = CMTime(seconds: seconds, preferredTimescale: 48_000) }
    var now: CMTime { lock.lock(); defer { lock.unlock() }; return time }
    func set(_ seconds: Double) { lock.lock(); defer { lock.unlock() }; time = CMTime(seconds: seconds, preferredTimescale: 48_000) }
}

private final class RecordingCompositionSmokeStops: @unchecked Sendable {
    private let lock = NSLock()
    private var stored: String?
    var message: String? { lock.lock(); defer { lock.unlock() }; return stored }
    func record(_ message: String?) { lock.lock(); defer { lock.unlock() }; if stored == nil { stored = message ?? "automatic limit" } }
}
